# EXECUTION PRINCIPALE
# ============================================================
if __name__ == "__main__":

    print("=" * 70)
    print("  FUSION DES CSV - TUNISIE JOB BOARDS")
    print(f"  Cible : 420+420+420+150 = 1 410 jobs")
    print(f"  Output: {OUTPUT_CSV}")
    print("=" * 70)

    frames = []
    total_cible = sum(limite for _, _, limite in FICHIERS)

    for path, label, limite in FICHIERS:
        df_src = charger_csv(path, label, limite)
        if not df_src.empty:
            frames.append(df_src)

    if not frames:
        print("\n  ERREUR : Aucun fichier source disponible.")
        exit(1)

    # Concatenation SANS dedoublonnage cross-sources
    df_all = pd.concat(frames, ignore_index=True)

    print(f"\n{'=' * 70}")
    print(f"  Lignes apres concat : {len(df_all):,} / {total_cible:,}")

    # Repartition par source
    print(f"\n  Repartition par source :")
    cibles = {label: limite for _, label, limite in FICHIERS}
    for src, cnt in df_all['Source'].value_counts().items():
        cible_src = cibles.get(src, 0)
        statut = "OK" if cnt >= cible_src else f"MANQUE {cible_src - cnt}"
        barre = '#' * (cnt // 20)
        print(f"    {src:<20} {cnt:>4} / {cible_src:<4}  {statut}  {barre}")

    # Remplacement valeurs nulles textuelles
    df_all.replace(NULL_VALS, np.nan, inplace=True)

    # Normalisation Date_Publication
    if 'Date_Publication' in df_all.columns:
        df_all['Date_Publication'] = pd.to_datetime(
            df_all['Date_Publication'], errors='coerce'
        ).dt.strftime('%Y-%m-%d')

    # Tri par source (ordre FICHIERS) puis date decroissante
    ordre_source = {label: i for i, (_, label, _) in enumerate(FICHIERS)}
    df_all['_ordre'] = df_all['Source'].map(ordre_source)
    df_all.sort_values(['_ordre', 'Date_Publication'],
                       ascending=[True, False], inplace=True)
    df_all.drop(columns=['_ordre'], inplace=True)
    df_all.reset_index(drop=True, inplace=True)

    # Sauvegarde
    df_all.to_csv(OUTPUT_CSV, index=False, encoding='utf-8-sig')

    # ══════════════════════════════════════════════════════════
    # RAPPORT FINAL
    # ══════════════════════════════════════════════════════════
    print(f"\n{'=' * 70}")
    print(f"  RAPPORT FINAL")
    print(f"{'=' * 70}")
    print(f"  Total jobs             : {len(df_all):,} / {total_cible:,}")
    print(f"  Colonnes               : {len(df_all.columns)} -> {list(df_all.columns)}")
    print(f"  Fichier                : {os.path.abspath(OUTPUT_CSV)}")

    print(f"\n  Completude des colonnes :")
    for col in df_all.columns:
        non_null = df_all[col].notna().sum()
        pct = non_null / len(df_all) * 100 if len(df_all) > 0 else 0
        barre = '#' * int(pct / 5) + '.' * (20 - int(pct / 5))
        print(f"    {col:<25} [{barre}] {pct:5.1f}%  ({non_null:,}/{len(df_all):,})")

    print(f"\n  Repartition par source (finale) :")
    for src, cnt in df_all['Source'].value_counts().items():
        cible_src = cibles.get(src, 0)
        statut = "OK" if cnt >= cible_src else f"MANQUE {cible_src - cnt}"
        barre = '#' * (cnt // 20)
        print(f"    {src:<20} {cnt:>4} / {cible_src:<4}  {statut}  {barre}")

    print(f"\n  Top 10 Type_Contrat :")
    for val, cnt in df_all['Type_Contrat'].value_counts(dropna=False).head(10).items():
        print(f"    {str(val):<35} {cnt:>4}")

    print(f"\n  Top 10 villes :")
    for val, cnt in df_all['Lieu'].value_counts(dropna=False).head(10).items():
        print(f"    {str(val):<35} {cnt:>4}")

    print(f"\n  Top 10 categories :")
    for val, cnt in df_all['Categories'].value_counts(dropna=False).head(10).items():
        print(f"    {str(val):<40} {cnt:>4}")

    # Affichage COMPLET - toutes les colonnes, tous les jobs
    print(f"\n{'=' * 70}")
    print(f"  LISTE COMPLETE - {len(df_all):,} JOBS (toutes colonnes)")
    print(f"{'=' * 70}")
    print(df_all.to_string(index=True))

    print(f"\n{'=' * 70}")
    if len(df_all) < total_cible:
        print(f"  ATTENTION : Il manque {total_cible - len(df_all):,} jobs.")
        print(f"  -> Wuzzuf et TunisieTravail n'ont que 150 jobs chacun.")
        print(f"  -> Relancez leurs scrapers avec MAX_JOBS = 420.")
    print(f"  Fusion terminee : {len(df_all):,} jobs -> {os.path.abspath(OUTPUT_CSV)}")
    print("=" * 70)

