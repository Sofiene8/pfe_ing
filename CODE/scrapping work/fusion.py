import pandas as pd
import numpy as np
import os

# ============================================================
# CONFIGURATION AFFICHAGE
# ============================================================
pd.set_option('display.max_columns', None)
pd.set_option('display.width', 2000)
pd.set_option('display.max_colwidth', 60)
pd.set_option('display.max_rows', 2000)
pd.set_option('display.expand_frame_repr', False)

# ============================================================
# FICHIERS A FUSIONNER
# Format : (fichier, source_label, limite_jobs)
# ============================================================
FICHIERS = [
    ("jobs_keejobs_420.csv",        "Keejob",         420),
    ("jobs_wuzzuf_420.csv",         "Wuzzuf",          420),
    ("jobs_tunisietravail_420.csv", "TunisieTravail",  420),
    ("jobs_tunijobs_420.csv",       "Tunijobs",        150),
]

OUTPUT_CSV = "jobs_all_1410.csv"

# Colonnes finales unifiees (union de toutes les sources)
# Wuzzuf ajoute : Skills, Education
COLONNES_CIBLES = [
    "Job_ID",
    "Titre",
    "Societe",
    "Description",
    "Skills",           # Wuzzuf uniquement (vide pour les autres)
    "Categories",
    "Annees_Experience",
    "Niveau_Experience",
    "Education",        # Wuzzuf uniquement (vide pour les autres)
    "Salaire",
    "Lieu",
    "Type_Contrat",
    "Mode_Travail",
    "Date_Publication",
    "Date_Relative",
    "Expire",
    "Source",
    "Lien",
]

NULL_VALS = ['N/A', 'n/a', 'NA', 'na', 'None', 'none', 'NaN', 'nan', '', ' ']

# ============================================================
# CHARGEMENT D'UN FICHIER SOURCE
# ============================================================
def charger_csv(path, source_label, limite):
    print(f"\n  -- {source_label} ({path}) --")

    if not os.path.exists(path):
        print(f"     ERREUR : fichier introuvable dans {os.getcwd()}")
        return pd.DataFrame()

    df = None
    for enc in ("utf-8-sig", "utf-8", "latin-1"):
        try:
            df = pd.read_csv(path, encoding=enc)
            if not df.empty:
                break
        except Exception:
            continue

    if df is None or df.empty:
        print(f"     ERREUR : fichier vide ou illisible")
        return pd.DataFrame()

    print(f"     Colonnes detectees       : {list(df.columns)}")
    print(f"     Lignes brutes            : {len(df):,}")

    # Strip espaces
    df = df.apply(lambda col: col.map(
        lambda x: x.strip() if isinstance(x, str) else x
    ))

    # Harmonisation colonne Titre
    col_titre = next(
        (c for c in ('Titre', 'Job Title', 'Title', 'titre') if c in df.columns), None
    )
    if col_titre and col_titre != 'Titre':
        df.rename(columns={col_titre: 'Titre'}, inplace=True)
        col_titre = 'Titre'

    # Drop lignes sans titre
    if col_titre:
        avant = len(df)
        df = df[df[col_titre].notna()]
        df = df[df[col_titre].astype(str).str.strip() != '']
        if avant - len(df) > 0:
            print(f"     Lignes sans titre supp.  : {avant - len(df):,}")

    # Dedoublonnage INTERNE sur Job_ID uniquement
    if 'Job_ID' in df.columns:
        avant = len(df)
        df.drop_duplicates(subset=['Job_ID'], keep='first', inplace=True)
        if avant - len(df) > 0:
            print(f"     Doublons Job_ID supprimes : {avant - len(df):,}")

    print(f"     Lignes apres nettoyage   : {len(df):,}")

    # Forcer la colonne Source
    df['Source'] = source_label

    # Ajouter les colonnes manquantes avec NaN
    for col in COLONNES_CIBLES:
        if col not in df.columns:
            df[col] = np.nan

    # Garder uniquement les colonnes cibles dans le bon ordre
    df = df[COLONNES_CIBLES].copy()

    # Limite
    disponible = len(df)
    df = df.head(limite)
    if disponible < limite:
        print(f"     ATTENTION : seulement {disponible} jobs dispo sur {limite} demandes")
        print(f"     -> Relancez le scraper {source_label} pour obtenir {limite} jobs")
    else:
        print(f"     OK : {len(df):,} jobs selectionnes")

    return df


